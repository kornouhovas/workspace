import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

test("electron main process uses an isolated preload shell with workspace IPC handlers", async () => {
  const mainSource = await readFile(new URL("../electron/main.js", import.meta.url), "utf8");

  assert.match(mainSource, /import \{ app, BrowserWindow, dialog, ipcMain \} from "electron"/);
  assert.match(mainSource, /app\.setName\("Workspace"\)/);
  assert.match(mainSource, /new BrowserWindow\(/);
  assert.match(mainSource, /title:\s*"Workspace"/);
  assert.match(mainSource, /contextIsolation:\s*true/);
  assert.match(mainSource, /nodeIntegration:\s*false/);
  assert.match(mainSource, /preload:\s*join\(__dirname,\s*"preload\.cjs"\)/);
  assert.match(mainSource, /window\.loadURL\("about:blank"\)/);
  assert.doesNotMatch(mainSource, /loadFile\(/);
  assert.match(mainSource, /import\s+\{\s*spawn\s*\}\s+from\s+"node:child_process"/);
  assert.match(mainSource, /import\s+\{\s*once\s*\}\s+from\s+"node:events"/);
  assert.match(mainSource, /import\s+\{\s*WorkspaceServiceClient\s*\}\s+from\s+"..\/src\/workspaceServiceClient\.js"/);
  assert.match(mainSource, /import\s+\{\s*createSidecarHttpTransport\s*\}\s+from\s+"\.\/sidecarClient\.js"/);
  assert.match(mainSource, /let\s+workspaceClient\s*=\s*null/);
  assert.match(mainSource, /let\s+sidecarProcess\s*=\s*null/);
  assert.match(mainSource, /const\s+sidecarStartupTimeoutMs\s*=\s*5000/);
  assert.match(mainSource, /async\s+function\s+startWorkspaceSidecar\(\)/);
  assert.match(mainSource, /function\s+resolveWorkspaceSidecarPath\(repoRoot\)/);
  assert.match(mainSource, /app\.isPackaged/);
  assert.match(mainSource, /process\.resourcesPath,\s*"sidecar"/);
  assert.match(mainSource, /function\s+getSidecarPlatformDirectory\(platform = process\.platform, arch = process\.arch\)/);
  assert.match(mainSource, /return "darwin-arm64"/);
  assert.match(mainSource, /return "win32-x64"/);
  assert.match(mainSource, /function\s+getSidecarExecutableName\(platform = process\.platform\)/);
  assert.match(mainSource, /"workspace-sidecar\.exe"/);
  assert.match(mainSource, /function\s+resolveWorkspaceSidecarCwd\(repoRoot\)/);
  assert.match(mainSource, /function\s+stopWorkspaceSidecar\(\)/);
  assert.match(mainSource, /const\s+sidecarPath\s*=\s*resolveWorkspaceSidecarPath\(repoRoot\)/);
  assert.match(mainSource, /const\s+sidecarCwd\s*=\s*resolveWorkspaceSidecarCwd\(repoRoot\)/);
  assert.match(mainSource, /spawn\(sidecarPath,\s*\["-db",\s*join\(app\.getPath\("userData"\),\s*"workspace\.db"\)\]/);
  assert.match(mainSource, /cwd:\s*sidecarCwd/);
  assert.match(mainSource, /childProcess\.stderr\.on\("data",\s*handleData\)/);
  assert.match(mainSource, /chunks\.join\(""\)\.match\(/);
  assert.match(mainSource, /Workspace sidecar startup timed out\./);
  assert.match(mainSource, /new\s+WorkspaceServiceClient\(createSidecarHttpTransport\(`http:\/\/\$\{address\}`\)\)/);
  assert.match(mainSource, /ipcMain\.handle\("workspace:getRoot"/);
  assert.match(mainSource, /ipcMain\.handle\("workspace:selectRoot",\s*async/);
  assert.match(mainSource, /createSelectRootResponse\(\{\s*configPath:\s*getWorkspaceSettingsPath\(\),\s*chooseRoot:\s*chooseElectronWorkspaceRoot/s);
  assert.match(mainSource, /dialog\.showOpenDialog\(\{/);
  assert.match(mainSource, /properties:\s*\["openDirectory"\]/);
  assert.match(mainSource, /function\s+getWorkspaceDataDirectory\(\)/);
  assert.match(mainSource, /app\.getPath\("userData"\),\s*"\.workspace"/);
  assert.match(mainSource, /function\s+getWorkspaceSettingsPath\(\)/);
  assert.match(mainSource, /function\s+getWorkspacePropertiesPath\(\)/);
  assert.match(mainSource, /ipcMain\.handle\("workspace:saveProperty",\s*async/);
  assert.match(mainSource, /ipcMain\.handle\("workspace:previewFile",\s*async/);
  assert.match(mainSource, /await\s+workspaceClient\.getRoot\(\)/);
  assert.match(mainSource, /await\s+workspaceClient\.setRoot\(/);
  assert.match(mainSource, /await\s+workspaceClient\.listPropertyValues\(/);
  assert.match(mainSource, /await\s+workspaceClient\.saveProperty\(/);
  assert.match(mainSource, /pathToFileURL\(response\.filePath\)\.href/);
  assert.match(mainSource, /function\s+attachStoredWorkspaceProperties\(rootPath,\s*payload\)/);
  assert.match(mainSource, /function\s+readSelectedWorkspaceRootPath\(\)/);
  assert.match(mainSource, /function\s+persistWorkspaceRoot\(rootPath\)/);
  assert.match(mainSource, /function\s+persistWorkspacePropertyValue\(rootPath,\s*body\)/);
  assert.match(mainSource, /function normalizePayload\(payload\)/);
  assert.match(mainSource, /app\.whenReady\(\)\.then\(async\s*\(\)\s*=>\s*\{/);
  assert.match(mainSource, /await\s+startWorkspaceSidecar\(\)/);
  assert.match(mainSource, /Workspace sidecar unavailable:/);
  assert.match(mainSource, /workspaceClient\s*=\s*null/);
});

test("electron preload exposes only the narrow workspace API", async () => {
  const preloadSource = await readFile(new URL("../electron/preload.cjs", import.meta.url), "utf8");

  assert.match(preloadSource, /require\("electron"\)/);
  assert.match(preloadSource, /contextBridge\.exposeInMainWorld\("workspace"/);
  assert.match(preloadSource, /getRoot:\s*\(\)\s*=>\s*ipcRenderer\.invoke\("workspace:getRoot"\)/);
  assert.match(preloadSource, /selectRoot:\s*\(\)\s*=>\s*ipcRenderer\.invoke\("workspace:selectRoot"\)/);
  assert.match(preloadSource, /scan:\s*\(payload\)\s*=>\s*ipcRenderer\.invoke\("workspace:scan",\s*payload\)/);
  assert.match(preloadSource, /listEntries:\s*\(payload\)\s*=>\s*ipcRenderer\.invoke\("workspace:listEntries",\s*payload\)/);
  assert.match(preloadSource, /saveProperty:\s*\(payload\)\s*=>\s*ipcRenderer\.invoke\("workspace:saveProperty",\s*payload\)/);
  assert.match(preloadSource, /previewFile:\s*\(payload\)\s*=>\s*ipcRenderer\.invoke\("workspace:previewFile",\s*payload\)/);
  assert.match(preloadSource, /reveal:\s*\(payload\)\s*=>\s*ipcRenderer\.invoke\("workspace:reveal",\s*payload\)/);
  assert.doesNotMatch(preloadSource, /require\("fs"\)/);
  assert.doesNotMatch(preloadSource, /from\s+["']electron["']/);
  assert.doesNotMatch(preloadSource, /from\s+["']node:fs["']/);
});
