import assert from "node:assert/strict";
import test from "node:test";
import React from "react";
import {Window} from "happy-dom";
import {StatusColorEditor} from "../src/renderer/components/StatusColorEditor.js";
import {FolderRolesPanel} from "../src/renderer/components/FolderRolesPanel.js";
import type {WorkspaceServiceClient} from "../src/renderer/workspace-service-client.js";
const browser=new Window({url:"http://localhost"});
Object.assign(globalThis,{window:browser,document:browser.document,HTMLElement:browser.HTMLElement,Node:browser.Node,Element:browser.Element,MutationObserver:browser.MutationObserver});
Object.defineProperty(globalThis,"navigator",{configurable:true,value:browser.navigator});
const {render,screen,cleanup,waitFor}=await import("@testing-library/react");
const {default:userEvent}=await import("@testing-library/user-event");
test.afterEach(()=>cleanup());
const category={categoryId:"first",relativePath:"Work",name:"Work",presentation:{categoryId:"first",color:"default" as const,hidden:false,position:0}};
for(const language of ["en","ru"] as const)test(`${language}: status editor saves by identity, disables pending, retains focus and exposes failure recovery`,async()=>{
 let finish:(result:unknown)=>void=()=>{};
 const calls:unknown[]=[];
 const client={setCategoryColor:(input:unknown)=>{calls.push(input);return new Promise(resolve=>{finish=resolve;});},listCategoryPresentation:async()=>({ok:true,value:{workspaceId:"one",options:[{categoryId:"first",color:"purple"}]}})} as unknown as WorkspaceServiceClient;
 const user=userEvent.setup({document:browser.document as unknown as Document});
 render(<StatusColorEditor client={client} workspaceId="one" category={category} language={language} disabled={false}/>);
 const select=screen.getByRole("combobox",{name:`${language==="en"?"Status color":"Цвет статуса"}: Work`});
 await user.selectOptions(select,"blue");assert.deepEqual(calls,[{workspaceId:"one",categoryId:"first",color:"blue"}]);
 assert.equal((select as HTMLSelectElement).disabled,true);
 finish({ok:true,value:{workspaceId:"one",options:[{categoryId:"first",color:"blue"}]}});
 await waitFor(()=>assert.equal((select as HTMLSelectElement).value,"blue"));
 await waitFor(()=>assert.equal(document.activeElement,select));
 await user.selectOptions(select,"red");finish({ok:false,error:{code:"storage"}});
 await screen.findByRole("alert");assert.equal((select as HTMLSelectElement).value,"blue");
 await user.click(screen.getByRole("button",{name:language==="en"?"Refresh":"Обновить"}));
 await waitFor(()=>assert.equal((select as HTMLSelectElement).value,"purple"));
 assert.equal(calls.length,2);
});
test('folder settings show committed status colors, preserve role drafts on color events and distinguish nested names',async()=>{
 let notify:(event:unknown)=>void=()=>{};
 const client={getFolderChildren:async(_id:string,path:string)=>({ok:true,value:{revision:1,state:"ready",folderRoles:[],excludedRelativePaths:[],children:path?[{relativePath:`${path}/Active`,name:"Active",role:"status",reason:null}]:["Clients","Personal"].map(name=>({relativePath:name,name,role:"group",reason:null}))}}),
 listProjects:async()=>({ok:true,value:{workspaceId:"one",categories:[{...category,relativePath:"Clients/Active",name:"Active"},{...category,categoryId:"second",relativePath:"Personal/Active",name:"Active",presentation:{color:"red",hidden:false,position:1}}]}}),onWorkspaceChange:(listener:typeof notify)=>{notify=listener;return()=>{};}} as unknown as WorkspaceServiceClient;
 const user=userEvent.setup({document:browser.document as unknown as Document});
 render(<FolderRolesPanel client={client} workspaceId="one" language="en" disabled={false} invalidation={0} onCommitted={()=>{}} onPendingChange={()=>{}}/>);
 await user.click(await screen.findByRole("button",{name:"Expand: Clients"}));await user.click(screen.getByRole("button",{name:"Expand: Personal"}));
 assert.equal((await screen.findByRole("combobox",{name:"Status color: Clients/Active"}) as HTMLSelectElement).value,"default");
 assert.equal((screen.getByRole("combobox",{name:"Status color: Personal/Active"}) as HTMLSelectElement).value,"red");
 await user.selectOptions(screen.getByRole("combobox",{name:"Role: Clients"}),"status");
 notify({type:"workspace.categoryPresentationChanged",workspaceIds:["one"]});
 await waitFor(()=>assert.equal((screen.getByRole("combobox",{name:"Role: Clients"}) as HTMLSelectElement).value,"status"));
 assert.equal((screen.getByRole("combobox",{name:"Status color: Clients/Active"}) as HTMLSelectElement).disabled,true);
});
test('a delayed save response cannot repaint a newer committed color from another entry point',async()=>{
 let finish:(result:unknown)=>void=()=>{};
 const client={setCategoryColor:()=>new Promise(resolve=>{finish=resolve;})} as unknown as WorkspaceServiceClient;
 const user=userEvent.setup({document:browser.document as unknown as Document});
 const props={client,workspaceId:"one",category,language:"en" as const,disabled:false};
 const {rerender}=render(<StatusColorEditor {...props}/>);
 const select=screen.getByRole("combobox",{name:"Status color: Work"});
 await user.selectOptions(select,"red");
 rerender(<StatusColorEditor {...props} category={{...category,presentation:{...category.presentation,color:"purple"}}}/>);
 await waitFor(()=>assert.equal((select as HTMLSelectElement).value,"purple"));
 finish({ok:true,value:{workspaceId:"one",options:[{categoryId:"first",color:"red"}]}});
 await waitFor(()=>assert.equal((select as HTMLSelectElement).disabled,false));
 assert.equal((select as HTMLSelectElement).value,"purple");
});
