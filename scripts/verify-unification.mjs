import { _electron as electron, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, writeFile, readFile, lstat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createWorkspaceIpcHandler } from '../electron/workspaceIpc.js';

const evidence = resolve(process.env.WORKSPACE_UNIFICATION_EVIDENCE || '.workspace-dev/unification');
await mkdir(evidence, { recursive: true });
const fixture = await mkdtemp(join(tmpdir(), 'workspace-unification-'));
const report = { fixture, checks: [], windows: [], errors: [] };
for (const [width, height] of [[1440, 960], [1024, 720]]) {
  const root = join(fixture, `projects-${width}`), metadata = join(fixture, `metadata-${width}`);
  await mkdir(join(root, 'Active', 'Alpha', 'docs'), { recursive: true });
  await mkdir(join(root, 'Active', 'Beta'), { recursive: true });
  await writeFile(join(root, 'Active', 'Alpha', 'docs', 'plan.txt'), 'retained');
  const options = { configPath: join(metadata, 'settings.json'), propertyStorePath: join(metadata, 'properties.json'), viewStorePath: join(metadata, 'views.json'), chooseRoot: async () => root };
  const handler = createWorkspaceIpcHandler(options);
  const { root: selected } = await handler(null, 'workspace.setRoot');
  const workspaceId = selected.workspaceId;
  const call = (method, payload = {}) => handler(null, `workspace.${method}`, { workspaceId, ...payload });
  await call('createProperty', { propertyId: 'property:notes', name: 'Notes', type: 'text' });
  await call('createProperty', { propertyId: 'property:hidden', name: 'Hidden note', type: 'text' });
  await call('updateProperty', { propertyId: 'property:hidden', patch: { hidden: true } });
  const { projection } = await call('getViewProjection', { viewId: 'view:default-table' });
  const id = projection.rows.find(project => project.name === 'Alpha').id;
  await call('updateProjectPropertyValue', { projectId: id, propertyId: 'property:notes', value: 'same' });
  const originalProperties = await readFile(options.propertyStorePath, 'utf8');
  const inode = (await lstat(join(root, 'Active', 'Alpha'))).ino;
  const app = await electron.launch({ args: ['electron/main.js'], cwd: process.cwd(), env: { ...process.env, WORKSPACE_DEV: '1', WORKSPACE_DEV_DATA: metadata, WORKSPACE_DEV_URL: '' } });
  let page;
  try {
    page = await app.firstWindow(); page.setDefaultTimeout(10000);
    page.on('pageerror', error => report.errors.push(error.message));
    await page.getByRole('button', { name: 'Alpha', exact: true }).waitFor();
    await app.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0].setBounds({ x: 0, y: 0, ...size }), { width, height });
    await page.waitForFunction(size => innerWidth === size.width && innerHeight === size.height, { width, height });
    const check = name => report.checks.push(`${width}x${height}: ${name}`);
    const right = page.getByTestId('workspace-right-panel');
    const renameDialog = page.locator('[data-workspace-rename-project]');
    const board = page.getByRole('tab', { name: 'Board', exact: true });
    const capture = async name => {
      await page.evaluate(() => document.fonts.ready);
      await page.screenshot({ path: join(evidence, `${name}-${width}x${height}.png`) });
    };
    for (const theme of ['light', 'dark']) {
      await page.evaluate(theme => localStorage.setItem('workspace.theme', theme), theme); await page.reload();
      await page.getByRole('button', { name: 'Alpha', exact: true }).click();
      await page.getByRole('dialog', { name: 'Alpha', exact: true }).waitFor();
      await expect.poll(() => page.locator('html').evaluate(element => element.classList.contains('dark'))).toBe(theme === 'dark');
      const labels = await page.locator('.workspace-navigation-chrome button').evaluateAll(buttons => buttons.map(button => button.getAttribute('aria-label')));
      assert.deepEqual(labels.slice(0, 3), ['Go back', 'Go forward', 'Hide sidebar']);
      const properties = right.getByRole('region', { name: 'Properties', exact: true });
      await expect(properties.locator('dl')).toHaveCount(1);
      await expect(properties.getByRole('heading')).toHaveCount(0);
      const hide = properties.getByRole('button', { name: 'Hide 1 property', exact: true });
      if (await hide.count()) await hide.click();
      const disclosure = properties.getByRole('button', { name: '1 more property', exact: true });
      await disclosure.click();
      await expect(properties.locator('[data-card-property-row-id="property:hidden"]')).toBeVisible();
      await properties.getByRole('button', { name: 'Hide 1 property', exact: true }).click();
      await expect(properties.locator('[data-card-property-row-id="property:hidden"]')).toBeHidden();
      const pencil = right.getByRole('button', { name: 'Rename project', exact: true });
      await pencil.focus(); await page.keyboard.press('Enter');
      await expect(renameDialog.getByRole('textbox', { name: 'Folder name', exact: true })).toHaveValue('Alpha');
      await renameDialog.getByRole('textbox').fill('Cancelled'); await page.keyboard.press('Escape');
      await expect(renameDialog).toHaveCount(0); await expect(pencil).toBeFocused();
      await capture(`preview-${theme}`);
      await right.getByRole('button', { name: /^Maximize pane/ }).click();
      const expanded = page.locator('.workspace-project-detail-expanded');
      await expanded.waitFor();
      const expandedPencil = page.getByTestId('workspace-main').getByRole('button', { name: 'Rename project', exact: true });
      await expandedPencil.focus(); await page.keyboard.press('Space');
      await renameDialog.getByRole('button', { name: 'Cancel', exact: true }).click();
      await expect(expandedPencil).toBeFocused();
      await capture(`expanded-${theme}`);
      await page.getByRole('button', { name: 'Close project details', exact: true }).last().click();
      await expect(board).toHaveAttribute('aria-selected', 'true');
      check(`${theme} preview/expanded pencils, Cancel/Escape focus, single properties list and disclosure`);
    }
    await page.getByRole('button', { name: 'Hide sidebar', exact: true }).click();
    await expect(page.locator('[data-sidebar-collapsed]')).toHaveAttribute('data-sidebar-collapsed', 'true');
    await page.getByRole('button', { name: 'Show sidebar', exact: true }).click();
    await expect(page.locator('[data-sidebar-collapsed]')).toHaveAttribute('data-sidebar-collapsed', 'false');
    await page.getByRole('button', { name: 'Customize Columns', exact: true }).click();
    const parent = page.locator('[data-workspace-view-filter-menu]');
    await page.getByRole('button', { name: 'Notes property actions', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Rename property', exact: true }).click();
    await expect(parent).toBeVisible(); await page.getByRole('textbox', { name: 'Rename property', exact: true }).press('Escape');
    await page.getByRole('button', { name: 'Customize Columns', exact: true }).click();
    await page.getByRole('button', { name: 'Customize Columns', exact: true }).click();
    await parent.locator('[data-workspace-group-trigger]').click();
    await parent.getByRole('combobox', { name: 'Group by', exact: true }).click();
    await page.getByRole('option', { name: 'Status', exact: true }).click();
    await parent.getByRole('combobox', { name: 'Sort', exact: true }).click();
    await page.getByRole('option', { name: 'Descending', exact: true }).click();
    await expect(parent).toBeVisible();
    await expect(parent.getByRole('combobox', { name: 'Sort', exact: true })).toHaveText('Descending');
    await page.getByRole('tab', { name: 'Table', exact: true }).click();
    await expect(parent).toHaveCount(0); await expect(board).toHaveAttribute('aria-selected', 'true');
    await page.getByRole('tab', { name: 'Table', exact: true }).click();
    await expect(page.getByRole('tab', { name: 'Table', exact: true })).toHaveAttribute('aria-selected', 'true');
    await board.click();
    check('Back/Forward/Sidebar order, sidebar restore, nested property/group/sort portals and first outside click dismissal');
    await page.getByRole('button', { name: 'Alpha', exact: true }).click();
    await right.getByRole('button', { name: 'Rename project', exact: true }).click();
    await renameDialog.getByRole('textbox').fill('Beta');
    await renameDialog.getByRole('button', { name: 'Rename', exact: true }).click();
    await expect(renameDialog.getByRole('alert')).toHaveText('A file or folder with this name already exists.');
    await expect(renameDialog.getByRole('textbox')).toHaveValue('Beta');
    await renameDialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await app.evaluate(({ ipcMain }, config) => {
      const require = process.getBuiltinModule('module').createRequire(config.modulePath);
      const { registerWorkspaceIpc } = require(config.modulePath);
      globalThis.renameWaiting = false;
      const gate = new Promise(resolve => { globalThis.releaseRename = resolve; });
      ipcMain.removeHandler('workspace:request');
      registerWorkspaceIpc(ipcMain, { ...config.options, renameTestHooks: { beforeStage: async () => { globalThis.renameWaiting = true; await gate; } } });
    }, { modulePath: resolve('electron/workspaceIpc.js'), options: { ...options, chooseRoot: undefined } });
    await right.getByRole('button', { name: 'Rename project', exact: true }).click();
    await renameDialog.getByRole('textbox').fill('Renamed');
    await renameDialog.getByRole('button', { name: 'Rename', exact: true }).click();
    await expect.poll(() => app.evaluate(() => globalThis.renameWaiting)).toBe(true);
    await expect(renameDialog.getByRole('button', { name: 'Cancel', exact: true })).toBeDisabled();
    await expect(renameDialog.getByRole('button', { name: 'Rename', exact: true })).toBeDisabled();
    await page.keyboard.press('Escape'); await expect(renameDialog).toBeVisible();
    await renameDialog.getByRole('button', { name: 'Show project rename', exact: true }).click();
    await expect(renameDialog).toContainText('Active/Alpha'); await expect(renameDialog).toContainText('Active/Renamed');
    await app.evaluate(() => globalThis.releaseRename());
    await expect(renameDialog).toHaveCount(0);
    await expect(page.getByRole('dialog', { name: 'Renamed', exact: true })).toBeVisible();
    assert.equal((await lstat(join(root, 'Active', 'Renamed'))).ino, inode);
    assert.equal(await readFile(join(root, 'Active', 'Renamed', 'docs', 'plan.txt'), 'utf8'), 'retained');
    assert.equal(await readFile(options.propertyStorePath, 'utf8'), originalProperties);
    const project = await page.evaluate(async ({ workspaceId, id }) => (await window.workspace.request('workspace.getProject', { workspaceId, projectId: id })).project, { workspaceId, id });
    assert.equal(project.id, id); assert.equal(project.name, 'Renamed'); assert.equal(project.propertyValues['property:notes'], 'same');
    await capture('rename-completed');
    await page.reload(); await page.getByRole('dialog', { name: 'Renamed', exact: true }).waitFor();
    check('Real preload/backend rename: no-clobber error draft, pending guard, unchanged inode/content/identity/values/history and reload');
    await right.getByRole('button', { name: /^Maximize pane/ }).click();
    await board.click();
    await page.evaluate(workspaceId => {
      const tabs = JSON.parse(localStorage.getItem('workspace.project-tabs.v1')).tabs[workspaceId];
      const layouts = JSON.parse(localStorage.getItem('workspace.pane-layout.v1'));
      layouts.layouts[workspaceId] = { ...layouts.layouts[workspaceId], rightVisible: false, focused: 'workspace', maximized: null, tree: { type: 'split', dir: 'row', sizes: [0.5, 0.5], children: [{ type: 'pane', paneId: 'workspace', tabId: null }, { type: 'pane', paneId: 'renamed-pane', tabId: tabs[0].tabId }] } };
      localStorage.setItem('workspace.pane-layout.v1', JSON.stringify(layouts));
    }, workspaceId);
    await page.reload();
    const splitPane = page.locator('[data-pane-id="renamed-pane"]');
    const splitPencil = splitPane.getByRole('button', { name: 'Rename project', exact: true });
    await expect(splitPencil).toHaveCount(1);
    await splitPencil.focus(); await page.keyboard.press('Space');
    await expect(renameDialog.getByRole('textbox')).toHaveValue('Renamed');
    await renameDialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(splitPencil).toBeFocused();
    await capture('split-dark');
    check('Split project host retains the matching rename pencil and returns focus on Cancel');
    await page.waitForFunction(size => innerWidth === size.width && innerHeight === size.height, { width, height });
    const bounds = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getBounds());
    assert.equal(bounds.width, width); assert.equal(bounds.height, height);
    report.windows.push(bounds);
  } catch (error) {
    report.errors.push(error.stack || String(error));
    if (page) { await page.screenshot({ path: join(evidence, `failure-${width}.png`) }).catch(() => {}); await writeFile(join(evidence, `failure-${width}.txt`), await page.locator('body').innerText().catch(() => '')); }
    throw error;
  } finally {
    await app.close(); await writeFile(join(evidence, 'report.json'), JSON.stringify(report, null, 2));
  }
}
assert.deepEqual(report.errors, []);
console.log(`Unified feature checks passed: ${report.checks.length}; evidence: ${evidence}`);
